export type Dictionary = (typeof messages)[SupportedLocale];

export function resolveLocale(
  locale: Locale,
  systemLocale = "en",
): SupportedLocale {
  if (locale === "tr") return "tr";
  if (locale === "en") return "en";
  return systemLocale.toLowerCase().startsWith("tr") ? "tr" : "en";
}
